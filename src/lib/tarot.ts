/** Детерминированный PRNG: одинаковый seed — одинаковый расклад. */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hashString(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** Дата в виде YYYY-MM-DD — расклад стабилен в пределах одних суток. */
export function todayKey(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

export interface DrawnCard {
  position: SpreadPosition;
  card: ArcanaCard;
  /** Значение карты применительно к выбранной теме */
  context: string;
}

export interface Reading {
  topic: TopicId;
  spreadName: string;
  cards: DrawnCard[];
  benefits: string[];
}

/**
 * Тянет расклад детерминированно: имя + тема + дата дают один и тот же
 * набор карт при каждом открытии страницы в течение суток.
 */
export function drawReading(name: string, topic: TopicId, dateKey = todayKey()): Reading {
  const spread = SPREADS[topic];
  const seed = hashString(`${name.trim().toLowerCase()}|${topic}|${dateKey}`);
  const random = mulberry32(seed);

  const deck = [...MAJOR_ARCANA];
  for (let i = deck.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }

  const cards: DrawnCard[] = spread.positions.map((position, index) => {
    const card = deck[index % deck.length];
    return { position, card, context: card.topic_contexts[topic] };
  });

  return { topic, spreadName: spread.name, cards, benefits: spread.benefits };
}
